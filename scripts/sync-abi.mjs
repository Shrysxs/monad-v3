// Regenerates lib/chain/abis/registry-abi.ts from the Foundry build output.
// Run after changing the contract: npm run contracts:build && npm run abi:sync
import { readFileSync, writeFileSync } from "node:fs";

const artifact = JSON.parse(
  readFileSync(new URL("../contracts/out/SwarmTraceRegistry.sol/SwarmTraceRegistry.json", import.meta.url), "utf8")
);
const out = `// AUTO-GENERATED by scripts/sync-abi.mjs from the Foundry artifact. Do not edit.
export const REGISTRY_ABI = ${JSON.stringify(artifact.abi, null, 2)} as const;
`;
writeFileSync(new URL("../lib/chain/abis/registry-abi.ts", import.meta.url), out);
console.log("Wrote lib/chain/abis/registry-abi.ts");
